@Suite struct ShelfClipRulesTests {
    private let ignored = Set(ShelfClipRules.defaultIgnoredApps)

    @Test func concealedTransientAndAutoGeneratedAreNeverRecorded() {
        let text = ShelfPasteboardTypes.string
        #expect(ShelfClipRules.skipReason(types: [text, ShelfPasteboardTypes.concealed], frontmostBundleID: nil, ignoredApps: []) == .concealed)
        #expect(ShelfClipRules.skipReason(types: [text, ShelfPasteboardTypes.transient], frontmostBundleID: nil, ignoredApps: []) == .transient)
        #expect(ShelfClipRules.skipReason(types: [text, ShelfPasteboardTypes.autoGenerated], frontmostBundleID: nil, ignoredApps: []) == .autoGenerated)
        #expect(ShelfClipRules.skipReason(types: [text, "de.petermaurer.TransientPasteboardType"], frontmostBundleID: nil, ignoredApps: []) == .transient)
        // Concealed wins over everything else, also in an allowed app.
        #expect(ShelfClipRules.skipReason(types: [ShelfPasteboardTypes.transient, ShelfPasteboardTypes.concealed],
                                          frontmostBundleID: "com.apple.TextEdit", ignoredApps: ignored) == .concealed)
    }

    @Test func ignoredAppsAreSkippedByFrontmostApp() {
        #expect(ShelfClipRules.skipReason(types: [ShelfPasteboardTypes.string], frontmostBundleID: "com.1password.1password", ignoredApps: ignored) == .ignoredApp)
        #expect(ShelfClipRules.skipReason(types: [ShelfPasteboardTypes.string], frontmostBundleID: "com.apple.Passwords", ignoredApps: ignored) == .ignoredApp)
        #expect(ShelfClipRules.skipReason(types: [ShelfPasteboardTypes.string], frontmostBundleID: "com.apple.TextEdit", ignoredApps: ignored) == nil)
        #expect(ShelfClipRules.skipReason(types: [], frontmostBundleID: nil, ignoredApps: ignored) == .empty)
    }

    @Test func passwordManagersArePreListed() {
        for id in ["com.apple.Passwords", "com.1password.1password", "com.bitwarden.desktop", "org.keepassxc.keepassxc"] {
            #expect(ShelfClipRules.defaultIgnoredApps.contains(id))
        }
    }
}

@Suite struct ShelfClipClassifierTests {
    private func candidate(_ content: ShelfPasteboardContent) -> ShelfClipCandidate? {
        if case .success(let value) = ShelfClipClassifier.candidate(from: content) { return value }
        return nil
    }

    @Test func filesWinOverTheirNames() {
        let content = ShelfPasteboardContent(plainText: "a.txt", filePaths: ["/tmp/a.txt", "/tmp/b.txt"])
        let clip = candidate(content)
        #expect(clip?.kind == .files)
        #expect(clip?.filePaths == ["/tmp/a.txt", "/tmp/b.txt"])
    }

    @Test func linksFromURLTypeOrPlainText() {
        #expect(candidate(ShelfPasteboardContent(plainText: "Example", url: "https://example.com/a"))?.kind == .url)
        #expect(candidate(ShelfPasteboardContent(plainText: "https://example.com/a"))?.url == "https://example.com/a")
        #expect(candidate(ShelfPasteboardContent(plainText: "  https://example.com  \n"))?.kind == .url)
        #expect(candidate(ShelfPasteboardContent(plainText: "see https://example.com now"))?.kind == .text)
        #expect(candidate(ShelfPasteboardContent(plainText: "mailto:someone@example.com"))?.kind == .url)
        #expect(ShelfClipClassifier.webURL("example.com") == nil)
        #expect(ShelfClipClassifier.webURL("file:///etc/hosts") == nil)
    }

    @Test func richTextKeepsPlainAndRTF() {
        let rtf = Data("{\\rtf1 hello}".utf8)
        let clip = candidate(ShelfPasteboardContent(plainText: "hello", rtf: rtf))
        #expect(clip?.kind == .richText)
        #expect(clip?.text == "hello")
        #expect(clip?.rtf == rtf)
        // Styled and plain copies of the same words are the same clip.
        #expect(clip?.fingerprint == candidate(ShelfPasteboardContent(plainText: "hello"))?.fingerprint)
    }

    @Test func imageOnlyWithoutText() {
        let png = Data([0x89, 0x50, 0x4E, 0x47, 1, 2, 3])
        #expect(candidate(ShelfPasteboardContent(image: png, imagePixelSize: CGSize(width: 10, height: 20)))?.kind == .image)
        #expect(candidate(ShelfPasteboardContent(plainText: "caption", image: png))?.kind == .text)
    }

    @Test func emptyAndOversizedAreSkipped() {
        #expect(throws: ShelfClipSkipReason.empty) { try ShelfClipClassifier.candidate(from: ShelfPasteboardContent(plainText: "  \n ")).get() }
        let huge = String(repeating: "x", count: ShelfClipClassifier.maxTextLength + 1)
        #expect(throws: ShelfClipSkipReason.tooLarge) { try ShelfClipClassifier.candidate(from: ShelfPasteboardContent(plainText: huge)).get() }
    }

    @Test func previewIsOneLine() {
        #expect(ShelfClip.oneLine("\n\n  first   line \nsecond") == "first line")
        #expect(ShelfClip.oneLine(String(repeating: "a", count: 300)).count == 241)
    }
}

@Suite struct ShelfClipHistoryTests {
    private let t0 = Date(timeIntervalSince1970: 1_800_000_000)

    private func text(_ value: String) -> ShelfClipCandidate {
        if case .success(let candidate) = ShelfClipClassifier.candidate(from: ShelfPasteboardContent(plainText: value)) { return candidate }
        Issue.record("no candidate for \(value)")
        return ShelfClipCandidate(kind: .text, fingerprint: value)
    }

    @Test func repeatsMoveToTheTopInsteadOfDuplicating() {
        var history = ShelfClipHistory()
        let first = history.record(text("alpha"), source: "com.a", now: t0)
        history.record(text("beta"), source: "com.b", now: t0 + 1)
        guard case .inserted(let id) = first else { Issue.record("not inserted"); return }
        history.setPinned(id, true)
        let again = history.record(text("alpha"), source: "com.c", now: t0 + 2)
        #expect(again == .moved(id))
        #expect(history.clips.count == 2)
        #expect(history.clips.first?.id == id)
        #expect(history.clips.first?.isPinned == true)
        #expect(history.clips.first?.firstCopied == t0)
        #expect(history.clips.first?.lastCopied == t0 + 2)
    }

    @Test func countAndAgeCapsSparePinnedClips() {
        var history = ShelfClipHistory()
        for index in 0..<10 { history.record(text("clip \(index)"), source: nil, now: t0 + Double(index)) }
        let oldest = history.clips.last!.id
        history.setPinned(oldest, true)
        let removed = history.prune(now: t0 + 10, limit: 3, maxAge: 3600)
        #expect(removed.count == 6)
        #expect(history.clips.count == 4)   // 3 newest + the pinned one
        #expect(history.clips.contains { $0.id == oldest })
        let aged = history.prune(now: t0 + 10 + 7200, limit: 100, maxAge: 3600)
        #expect(aged.count == 3)
        #expect(history.clips.map(\.id) == [oldest])
    }

    @Test func clearDeleteAndRemoveAll() {
        var history = ShelfClipHistory()
        history.record(text("a"), source: nil, now: t0)
        history.record(text("b"), source: nil, now: t0 + 1)
        history.record(text("c"), source: nil, now: t0 + 2)
        let pinned = history.clips[1].id
        history.setPinned(pinned, true)
        #expect(history.delete(history.clips[0].id)?.text == "c")
        #expect(history.clearUnpinned().count == 1)
        #expect(history.clips.map(\.id) == [pinned])
        #expect(history.removeAll().count == 1)
        #expect(history.clips.isEmpty)
    }

    @Test func searchIgnoresCaseAndDiacriticsAndListsPinnedFirst() {
        var history = ShelfClipHistory()
        history.record(text("Café menu"), source: nil, now: t0)
        history.record(text("cafe hours"), source: nil, now: t0 + 1)
        history.record(text("unrelated"), source: nil, now: t0 + 2)
        history.setPinned(history.clips[2].id, true)
        #expect(history.visible(matching: "CAFE").map(\.text) == ["Café menu", "cafe hours"])
        #expect(history.visible(matching: "cafe menu").map(\.text) == ["Café menu"])
        #expect(history.visible(matching: "").first?.text == "Café menu")   // pinned first
        #expect(history.visible(matching: "zzz").isEmpty)
    }

    @Test func touchMovesACopiedBackClipToTheTop() {
        var history = ShelfClipHistory()
        history.record(text("a"), source: nil, now: t0)
        history.record(text("b"), source: nil, now: t0 + 1)
        let a = history.clips[1].id
        history.touch(a, now: t0 + 5)
        #expect(history.clips.first?.id == a)
    }
}

/// The monitor on a private named pasteboard: the user's clipboard is never touched.
@Suite(.serialized) struct ShelfClipboardMonitorTests {
    @Test func recordsWhatTheRulesAllowAndCopiesBackToTheSamePasteboard() throws {
        let pasteboard = NSPasteboard(name: NSPasteboard.Name("com.alphapengwang.rolltop.tests.shelf.\(UUID().uuidString)"))
        defer { pasteboard.releaseGlobally() }
        #expect(pasteboard.name != .general)
        let monitor = ShelfClipboardMonitor(pasteboard: pasteboard, interval: 10)
        var outcomes: [ShelfClipboardMonitor.Outcome] = []
        monitor.onOutcome = { outcomes.append($0) }
        monitor.start()
        defer { monitor.stop() }

        pasteboard.clearContents()
        pasteboard.setString("hello", forType: .string)
        monitor.poll()
        pasteboard.clearContents()
        let secret = NSPasteboardItem()
        secret.setString("hunter2", forType: .string)
        secret.setString("", forType: NSPasteboard.PasteboardType(ShelfPasteboardTypes.concealed))
        pasteboard.writeObjects([secret])
        monitor.poll()
        monitor.poll()   // no change: nothing new

        #expect(outcomes.count == 2)
        guard case .read(let read) = outcomes[0] else { Issue.record("first change not read"); return }
        #expect(read.content.plainText == "hello")
        guard case .skipped(.concealed) = outcomes[1] else { Issue.record("concealed entry not skipped"); return }

        // Copy back: lands on the same private pasteboard and is not re-read.
        let clip = ShelfClip(id: UUID(), kind: .url, text: "Example", url: "https://example.com", firstCopied: Date(), lastCopied: Date(),
                             fingerprint: "x")
        #expect(monitor.write(clip, image: nil))
        #expect(pasteboard.string(forType: .URL) == "https://example.com")
        outcomes.removeAll()
        monitor.poll()
        #expect(outcomes.isEmpty)
    }

    @Test func imagesAreDownscaled() throws {
        let image = NSImage(size: NSSize(width: 400, height: 200), flipped: false) { rect in
            NSColor.systemTeal.setFill()
            rect.fill()
            return true
        }
        let tiff = try #require(image.tiffRepresentation)
        let capped = try #require(ShelfClipboardMonitor.cappedPNG(tiff, maxPixels: 100))
        #expect(max(capped.size.width, capped.size.height) <= 100)
        #expect(capped.data.starts(with: [0x89, 0x50, 0x4E, 0x47]))
    }
}
